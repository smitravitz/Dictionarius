"""Tests for the chat-trace guard (scripts/chat_traces.py, .github/chat-traces.txt).

Run: python -m unittest scripts/test_chat_traces.py

The traces in these tests are put together from pieces, so this file doesn't carry any
itself: the hooks would refuse to write it, and the guard would flag it on every push. And no
assertion here prints a trace when it fails: CI's log is public on a public repository. Text
that might still hold one is checked with no_trace() first, which says only that it does.
"""

import json
import os
import subprocess
import sys
import tempfile
import unittest
from pathlib import Path

sys.path.insert(0, os.path.dirname(__file__))
import chat_traces  # noqa: E402

AI = "claude" + ".ai"
COM = "claude" + ".com"
SESSION_ID = "session" + "_01" + "AbCdEfGhIjKlMnOp"
TRAILER = "Claude" + "-Session"
SESSION_LINK = f"https://{AI}/code/{SESSION_ID}"
# Allowed, as they link to no chat: what a Claude session's GitHub access adds under a pull
# request it writes, and Claude Code's own attribution badge.
FOOTER = "_Generated " + "by [Claude Code](https://" + AI + "/code)_"
BADGE = "🤖 Generated " + "with [Claude Code](https://" + COM + "/claude-code)"


class Case(unittest.TestCase):
    def no_trace(self, text, where="the result"):
        self.assertFalse(bool(chat_traces.find(text)), f"a chat trace is left in {where}")

    def same(self, actual, expected):
        """assertEqual, for text that may hold a trace: checked first, so a failure can't print one."""
        self.no_trace(json.dumps(actual, ensure_ascii=False))
        self.assertEqual(actual, expected)


class FindsTraces(Case):
    def test_finds_every_kind_of_chat_trace(self):
        traces = {
            "a session's link": SESSION_LINK,
            "a session's link without its scheme": f"{AI}/code/{SESSION_ID}",
            "a chat's link": f"https://{AI}/chat/0f3c9a1e-77d2-4b8e-9a51-0c1d2e3f4a5b",
            "a shared chat's link": f"https://{AI}/share/5e6f7a8b",
            "a project's link": f"https://{AI}/project/9c0d1e2f",
            "a bare session id": f"see {SESSION_ID}",
            "the session trailer": f"{TRAILER}: {SESSION_LINK}",
            "the trailer, in lower case": f"{TRAILER.lower()}: x",
        }
        for what, trace in traces.items():
            with self.subTest(what):
                found = chat_traces.find(f"Fix the list.\n\n{trace}\nMore text.\n")
                self.assertEqual([number for number, _ in found], [3], what)

    def test_leaves_what_the_owner_allows(self):
        allowed = [
            "Co-Authored-By: Claude Opus 5.5 <noreply@anthropic.com>",
            "The Claude Code hook in .claude/hooks blocks a commit that carries one.",
            "Read the API's guide at https://docs.anthropic.com first.",
            "The manifest is generated by tools/web-app.ts at build time.",
            "A session_id field, and the word session on its own.",
            "Claude wrote the first draft of this note.",
            FOOTER,
            BADGE,
            "Generated " + "with Claude Code",
            f"Claude Code on the web: https://{AI}/code",
            f"Made at https://{AI}.",
        ]
        for text in allowed:
            with self.subTest(text):
                self.assertEqual(chat_traces.find(text), [])

    def test_the_pattern_list_carries_no_trace_itself(self):
        # So the list can live in the repository, and be written by a hooked session.
        patterns = Path(chat_traces.PATTERNS).read_text(encoding="utf-8")
        self.assertEqual(chat_traces.find(patterns), [])


class RemovesTraces(Case):
    def test_takes_out_a_session_link_left_at_the_end_and_the_rule_above_it(self):
        body = "Two fixes for reopening.\n\nMerge this first.\n\n---\n" + SESSION_LINK
        self.same(chat_traces.remove(body), "Two fixes for reopening.\n\nMerge this first.")

    def test_keeps_the_footer_and_takes_out_the_session_link_under_it(self):
        body = "Two fixes.\n\n---\n" + FOOTER + "\n\n" + SESSION_LINK + "\n"
        self.same(chat_traces.remove(body), "Two fixes.\n\n---\n" + FOOTER)

    def test_takes_out_a_trace_line_and_keeps_every_other_line_as_it_was(self):
        body = "Fixes the list.\n\n- one\n- two\n\n" + SESSION_LINK + "\n\n## Tests\n\n  indented\n"
        self.same(chat_traces.remove(body), "Fixes the list.\n\n- one\n- two\n\n\n## Tests\n\n  indented\n")

    def test_a_line_that_names_a_session_goes_whole(self):
        body = f"Done.\nWritten in https://{AI}/code/{SESSION_ID} yesterday.\nThanks."
        self.same(chat_traces.remove(body), "Done.\nThanks.")

    def test_keeps_the_line_endings_a_browser_writes(self):
        body = "Two fixes.\r\n\r\nMerge first.\r\n\r\n---\r\n" + SESSION_LINK + "\r\n"
        self.same(chat_traces.remove(body), "Two fixes.\r\n\r\nMerge first.")

    def test_a_rule_with_more_after_it_stays(self):
        body = "Above.\n\n---\n\nBelow.\n" + SESSION_LINK
        self.same(chat_traces.remove(body), "Above.\n\n---\n\nBelow.")

    def test_text_with_no_trace_comes_back_unchanged(self):
        for body in ["", "One line", "Ends with a rule\n\n---\n", "Co-Authored-By: Claude <noreply@anthropic.com>\n", "Fixes.\n\n---\n" + FOOTER]:
            with self.subTest(body):
                self.same(chat_traces.remove(body), body)

    def test_a_title_loses_only_the_trace(self):
        self.same(chat_traces.remove_from_title(f"Fix the list (https://{AI}/code/{SESSION_ID})"), "Fix the list")
        self.same(chat_traces.remove_from_title(f"Fix the list, from {AI}/chat/0f3c9a1e"), "Fix the list, from")
        self.same(chat_traces.remove_from_title("Fix the list"), "Fix the list")


class HooksUseTheSameList(unittest.TestCase):
    """The git hooks and the Claude Code hook read .github/chat-traces.txt, as the workflow does."""

    ROOT = Path(__file__).resolve().parent.parent

    def git_hook(self, text):
        with tempfile.NamedTemporaryFile("w", suffix=".txt", delete=False) as file:
            file.write(text)
        self.addCleanup(os.unlink, file.name)
        return subprocess.run(["bash", str(self.ROOT / ".githooks/no-chat-links.sh"), file.name, "commit message"],
                              capture_output=True, text=True).returncode

    def claude_hook(self, command):
        call = json.dumps({"tool_name": "Bash", "tool_input": {"command": command}})
        return subprocess.run(["bash", str(self.ROOT / ".claude/hooks/no-chat-links.sh")], input=call,
                              capture_output=True, text=True, env={**os.environ, "CLAUDE_PROJECT_DIR": str(self.ROOT)}).returncode

    def test_both_hooks_stop_every_trace_the_workflow_finds_and_pass_what_it_allows(self):
        samples = {
            "a session's link": SESSION_LINK, "a chat's link": f"https://{AI}/chat/0f3c9a1e", "the trailer": f"{TRAILER}: x",
            "a session id": SESSION_ID, "the footer": FOOTER, "the badge": BADGE,
            "Claude Code on the web": f"https://{AI}/code", "the product page": f"https://{COM}/claude-code",
            "a co-author": "Co-Authored-By: Claude Opus 5.5 <noreply@anthropic.com>",
            "plain text": "Fix the list.", "a field's name": "A session_id field.",
        }
        for what, text in samples.items():
            with self.subTest(what):
                trace = bool(chat_traces.find(text))
                self.assertEqual(self.git_hook(text + "\n"), 1 if trace else 0)
                self.assertEqual(self.claude_hook(f"git commit -m '{text}'"), 2 if trace else 0)


if __name__ == "__main__":
    unittest.main()
