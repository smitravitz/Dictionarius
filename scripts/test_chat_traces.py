class Case(unittest.TestCase):
    def no_trace(self, text, where="the result"):
        self.assertFalse(bool(chat_traces.find(text)), f"a chat trace is left in {where}")

    def same(self, actual, expected):
        """assertEqual, for text that may hold a trace: checked first, so a failure can't print one."""
        self.no_trace(json.dumps(actual, ensure_ascii=False))
        self.assertEqual(actual, expected)


class FindsTraces(Case):
    def test_finds_every_kind_of_chat_trace(self):
        traces = {
            "a session's link": SESSION_LINK,
            "a session's link without its scheme": f"{AI}/code/{SESSION_ID}",
            "a chat's link": f"https://{AI}/chat/0f3c9a1e-77d2-4b8e-9a51-0c1d2e3f4a5b",
            "a shared chat's link": f"https://{AI}/share/5e6f7a8b",
            "a project's link": f"https://{AI}/project/9c0d1e2f",
            "a bare session id": f"see {SESSION_ID}",
            "the session trailer": f"{TRAILER}: {SESSION_LINK}",
            "the trailer, in lower case": f"{TRAILER.lower()}: x",
        }
        for what, trace in traces.items():
            with self.subTest(what):
                found = chat_traces.find(f"Fix the list.\n\n{trace}\nMore text.\n")
                self.assertEqual([number for number, _ in found], [3], what)

    def test_leaves_what_the_owner_allows(self):
        allowed = [
            "Co-Authored-By: Claude Opus 5.5 <noreply@anthropic.com>",
            "The Claude Code hook in .claude/hooks blocks a commit that carries one.",
            "Read the API's guide at https://docs.anthropic.com first.",
            "The manifest is generated by tools/web-app.ts at build time.",
            "A session_id field, and the word session on its own.",
            "Claude wrote the first draft of this note.",
            FOOTER,
            BADGE,
            "Generated " + "with Claude Code",
            f"Claude Code on the web: https://{AI}/code",
            f"Made at https://{AI}.",
        ]
        for text in allowed:
            with self.subTest(text):
                self.assertEqual(chat_traces.find(text), [])

    def test_the_pattern_list_carries_no_trace_itself(self):
        # So the list can live in the repository, and be written by a hooked session.
        patterns = Path(chat_traces.PATTERNS).read_text(encoding="utf-8")
        self.assertEqual(chat_traces.find(patterns), [])


